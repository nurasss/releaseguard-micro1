"""Generator script to produce docs/openapi.json from src/api/routes.py."""

import hashlib
import json
from pathlib import Path
from src.api.routes import ROUTES


def generate():
    source_path = Path("src/api/routes.py")
    source_hash = hashlib.sha256(source_path.read_bytes()).hexdigest()
    paths = {}
    for r in ROUTES:
        path = r["path"]
        method = r["method"].lower()
        if path not in paths:
            paths[path] = {}
        paths[path][method] = {
            "summary": r["summary"],
            "responses": {"200": {"description": "OK"}},
        }

    spec = {
        "openapi": "3.0.0",
        "info": {
            "title": "User API",
            "version": "1.5.0",
            "description": f"Generated by scripts/generate_openapi.py from src/api/routes.py (source_hash: {source_hash})",
        },
        "paths": paths,
    }
    Path("docs/openapi.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")


if __name__ == "__main__":
    generate()
